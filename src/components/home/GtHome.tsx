function buildLinks() {
  const L: Record<string, string> = {
    "Tüm Hizmetler": "/hizmetler", "Tüm Bölgeler": "/tesisatci", "Tüm Yazılar": "/blog",
    "Ücretsiz Keşif / Randevu": "/randevu", "Fiyatlar": "/fiyatlar",
  };
  for (const s of SERVICES) {
    L[s.name] = `/hizmet/${s.slug}`;
    L[`${s.name} Fiyatları`] = `/hizmet/${s.slug}/fiyat`;
  }
  // names used in the design that differ slightly from the service data
  const alias: Record<string, string> = {
    "Tuvalet Tıkanıklığı Açma": "tuvalet-tikanikligi-acma", "Mutfak & Lavabo Gider Açma": "mutfak-gider-acma",
    "Duşakabin & Vitrifiye Montajı": "dusakabin-vitrifiye-montaji", "Musluk & Batarya Değişimi": "musluk-batarya-degisimi",
    "Hidrofor Kurulumu & Arıza": "hidrofor-kurulumu", "Acil Tesisatçı 7/24": "acil-tesisatci",
  };
  for (const [n, slug] of Object.entries(alias)) {
    L[n] ??= `/hizmet/${slug}`;
    L[`${n} Fiyatları`] ??= `/hizmet/${slug}/fiyat`;
  }
  for (const d of DISTRICTS) L[`${d.name} Tesisatçı`] = `/tesisatci/${d.slug}`;
  for (const [t, slug] of Object.entries(FOOTER_GUIDES)) L[t] = `/blog/${slug}`;
  for (const p of FEATURED_POSTS) L[p.title] = `/blog/${p.slug}`;
  return L;
}

let scriptPromise: Promise<void> | null = null;
function loadRuntime() {
  if (scriptPromise) return scriptPromise;
  scriptPromise = new Promise((resolve, reject) => {
    const s = document.createElement("script");
    s.src = "/home/gt-home.js?v=6";
    s.async = true;
    s.onload = () => resolve();
    s.onerror = () => { scriptPromise = null; reject(new Error("gt-home runtime failed to load")); };
    document.body.appendChild(s);
  });
  return scriptPromise;
}

export function GtHome({ posts = [] }: { posts?: HomePost[] }) {
  const router = useRouter();
  useEffect(() => {
    const w = window as unknown as Record<string, unknown> & { GTHome?: { init: () => void } };
    w.__IMG = [boilerShell];
    w.__GT_IMG = IMG;
    w.__GT_LINKS = buildLinks();
    w.__GT_POSTS = posts;
    w.GT_THANKYOU_URL = "/tesekkurler";
    w.GT_NAVIGATE = (u: string) => { router.history.push(u); };
    w.GT_SAVE_BOOKING = (rec: BookingRecord) => saveBooking(rec, "home_popup");
    w.__gtHomeAuto = false;
    let alive = true;
    loadRuntime()
      .then(() => { if (alive) w.GTHome?.init(); })
      .catch((e) => console.warn(e));
    return () => { alive = false; };
  }, [posts]);

  return <div className="gt-home" suppressHydrationWarning dangerouslySetInnerHTML={{ __html: HTML }} />;
}
